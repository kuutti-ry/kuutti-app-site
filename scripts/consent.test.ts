test("the table pins every kind, each row a version and a fingerprint", () => {
  assert.deepEqual(Object.keys(PINNED), [...CONSENT_KINDS]);
  for (const kind of CONSENT_KINDS) {
    for (const [version, hash] of Object.entries(PINNED[kind])) {
      assert.match(version, CONSENT_VERSION, kind);
      assert.match(hash, /^[0-9a-f]{16}$/, `${kind} ${version}`);
    }
  }
});

test("a version is lower-case letters, digits, dots and hyphens, never digits alone", () => {
  for (const good of ["2026-09-draft-1", "2026-11-1", "v1", "1.2", "a"]) {
    assert.match(good, CONSENT_VERSION, good);
  }
  for (const bad of ["20261101", "1", "", "-1", "2026_11", "V1", "2026 11", "2026-11-1\n"]) {
    assert.doesNotMatch(bad, CONSENT_VERSION, bad);
  }
  // Why digits alone are refused: JavaScript lists such a key first.
  assert.deepEqual(Object.keys({ "2026-09-draft-1": "", "20261101": "" }), [
    "20261101",
    "2026-09-draft-1",
  ]);
});

