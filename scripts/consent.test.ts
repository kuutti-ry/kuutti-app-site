test("the app's versions are fetched from its main on GitHub, and a failed answer fails", async () => {
  const asked: string[] = [];
  const answering =
    (status: number, body: string): typeof fetch =>
    async (input) => {
      asked.push(String(input));
      return new Response(body, { status });
    };
  assert.deepEqual(await fetchAppVersions(answering(200, appModule(APP_TODAY))), APP_TODAY);
  assert.deepEqual(asked, [APP_VERSIONS_URL]);
  assert.match(
    APP_VERSIONS_URL,
    /^https:\/\/raw\.githubusercontent\.com\/kuutti-ry\/kuutti-app\/main\/packages\/i18n\/src\/generated\/consent\.ts$/,
  );
  await assert.rejects(fetchAppVersions(answering(404, "404: Not Found")), /answered 404/);
  await assert.rejects(fetchAppVersions(answering(200, "<html>")), /no CONSENT_VERSIONS object/);
});

test("a network failure or a 5xx is tried three times, the pauses growing; a 4xx is not", async () => {
  const pauses: number[] = [];
  const pause = async (ms: number) => {
    pauses.push(ms);
  };
  const answers = (...steps: (number | Error)[]): typeof fetch => {
    let at = 0;
    return async () => {
      const step = steps[at++];
      if (step === undefined) throw new Error("asked once too often");
      if (step instanceof Error) throw step;
      return new Response(step === 200 ? appModule(APP_TODAY) : "", { status: step });
    };
  };
  const failed = new TypeError("fetch failed");
  assert.deepEqual(
    await fetchAppVersions(answers(failed, 503, 200), APP_VERSIONS_URL, pause),
    APP_TODAY,
  );
  assert.deepEqual(pauses, [5_000, 10_000]);
  pauses.length = 0;
  await assert.rejects(
    fetchAppVersions(answers(failed, failed, failed), APP_VERSIONS_URL, pause),
    /fetch failed/,
  );
  assert.deepEqual(pauses, [5_000, 10_000]);
  pauses.length = 0;
  await assert.rejects(
    fetchAppVersions(answers(502, 502, 502), APP_VERSIONS_URL, pause),
    /answered 502/,
  );
  pauses.length = 0;
  await assert.rejects(fetchAppVersions(answers(404), APP_VERSIONS_URL, pause), /answered 404/);
  assert.deepEqual(pauses, []);
});

test("the pause between tries is on the clock by default, five seconds at first", async (t) => {
  t.mock.timers.enable({ apis: ["setTimeout"] });
  let calls = 0;
  const fetchImpl: typeof fetch = async () => {
    calls++;
    if (calls === 1) throw new TypeError("fetch failed");
    return new Response(appModule(APP_TODAY));
  };
  const reading = fetchAppVersions(fetchImpl);
  const settle = () => new Promise((resolve) => setImmediate(resolve));
  await settle();
  t.mock.timers.tick(4_999);
  await settle();
  assert.equal(calls, 1);
  t.mock.timers.tick(1);
  assert.deepEqual(await reading, APP_TODAY);
  assert.equal(calls, 2);
});

