import assert from "node:assert/strict";
import { test } from "node:test";
import { PINNED } from "../src/consent-versions.ts";
import {
  APP_VERSIONS_URL,
  anchorOf,
  appVersionsFrom,
  byLanguage,
  CONSENT_KINDS,
  CONSENT_VERSION,
  type ConsentKind,
  countedWording,
  earlierProblems,
  fetchAppVersions,
  fingerprint,
  fingerprintOf,
  historyProblems,
  isConsentKind,
  mirror,
  type Pinned,
  pinnedText,
  pinProblems,
  TEXT_OF,
  versionsDocument,
  type Wording,
} from "../src/lib/consent.ts";

const ORIGIN = new URL("https://kuutti.app");
const DAY = new Date("2026-10-06T00:00:00Z");

const wording = (
  kind: ConsentKind,
  language: Wording["language"],
  body: string,
  version = "v1",
): Wording => ({
  kind,
  language,
  version,
  dated: DAY,
  title: kind,
  body,
});

/** Every kind in Finnish at v1, each with a body of its own, and the table that pins them. */
const content = (): Wording[] => CONSENT_KINDS.map((kind) => wording(kind, "fi", `${kind} teksti`));
const pinnedFor = (wordings: Wording[]): Pinned => {
  const row = (kind: ConsentKind) => ({
    v1: fingerprintOf(
      wordings.find((w) => w.kind === kind && w.language === "fi") ?? { title: "", body: "" },
    ),
  });
  return {
    terms: row("terms"),
    privacy: row("privacy"),
    research: row("research"),
    special_category: row("special_category"),
  };
};

/** The app's generated module, as `pnpm i18n:build` writes it (packages/i18n/scripts/lib/compile.ts). */
const appModule = (versions: Record<string, string>) =>
  "// Generated by `pnpm i18n:build` from messages.yaml. Do not edit: CI fails on drift.\n" +
  "/** The consent_version each legal.<kind>.* wording belongs to: what a consent row must name to count (#46). */\n" +
  `export const CONSENT_VERSIONS: Readonly<Record<string, string>> = {\n${Object.entries(versions)
    .map(([kind, version]) => `  ${JSON.stringify(kind)}: ${JSON.stringify(version)},`)
    .join("\n")}\n};\n\n` +
  'export const CONSENT_TEXT_LOCALES: Readonly<Record<string, readonly string[]>> = {\n  "terms": ["en","fi"],\n};\n\n' +
  'export const CONSENT_TEXT_HASHES: Readonly<Record<string, string>> = {\n  "terms": "a947eb54ce1338cd",\n};\n';

const APP_TODAY = {
  privacy: "2026-09-draft-1",
  research: "2026-09-draft-1",
  special_category: "2026-10-draft-2",
  terms: "2026-09-draft-1",
};

test("the kinds are the app's four, and each is read on a legal text", () => {
  assert.deepEqual([...CONSENT_KINDS], ["terms", "privacy", "research", "special_category"]);
  for (const kind of CONSENT_KINDS) assert.equal(isConsentKind(kind), true);
  for (const other of ["", "bylaws", "Terms", "special-category", "toString"]) {
    assert.equal(isConsentKind(other), false, other);
  }
  assert.equal(TEXT_OF.research, "privacy");
  assert.equal(TEXT_OF.special_category, "privacy");
  assert.equal(TEXT_OF.terms, "terms");
});

test("a version's anchor names the kind and the version", () => {
  assert.equal(anchorOf("research", "2026-09-draft-1"), "research-2026-09-draft-1");
  assert.equal(anchorOf("special_category", "2026-10-draft-2"), "special_category-2026-10-draft-2");
});

test("a fingerprint is 16 hex digits of the text, whatever its line ends and blank edges", () => {
  const print = fingerprint("Ensimmäinen rivi.\n\nToinen rivi.");
  assert.match(print, /^[0-9a-f]{16}$/);
  assert.equal(fingerprint("\n\nEnsimmäinen rivi.\r\n\r\nToinen rivi.\n"), print);
  assert.equal(fingerprint("Ensimmäinen rivi.\r\rToinen rivi."), print);
  assert.notEqual(fingerprint("Ensimmäinen rivi.\nToinen rivi."), print, "a line is a change");
  assert.notEqual(fingerprint("Ensimmäinen rivi. \n\nToinen rivi."), print, "a space is a change");
  assert.notEqual(fingerprint("ensimmäinen rivi.\n\nToinen rivi."), print, "a letter is a change");
  // The same digest as the app's (sha256, hex, the first 16).
  assert.equal(fingerprint(""), "e3b0c44298fc1c14");
});

test("a version pins the heading and the body, and a legal text's status and binding too", () => {
  assert.equal(
    pinnedText({ title: " Tutkimus ", body: "\r\nLUONNOS: teksti.\r\n" }),
    "# Tutkimus\n\nLUONNOS: teksti.",
  );
  assert.equal(
    pinnedText({ title: "Terms", body: "Text.", standing: { status: "draft", binding: false } }),
    "# Terms\nstatus: draft, binding: false\n\nText.",
  );
  // The app's check:legal-versions computes the research and sensitive-answers
  // fingerprint from its Finnish legal.<kind>.title and summary; its test
  // holds the same pair to the same value (legal-versions.test.ts there).
  assert.equal(
    fingerprintOf({ title: "Tutkimus", body: "LUONNOS: teksti.\r\n" }),
    "3db7397d9d6d2d5c",
  );
  const terms = { title: "Terms", body: "Text.", standing: { status: "draft", binding: false } };
  const moved = [
    { ...terms, title: "Terms of use" },
    { ...terms, standing: { status: "in_force", binding: false } },
    { ...terms, standing: { status: "draft", binding: true } },
    { ...terms, body: "Text!" },
  ];
  for (const other of moved) {
    assert.notEqual(fingerprintOf(other), fingerprintOf(terms), JSON.stringify(other));
  }
});

test("the Finnish text is the counted one; without it, a draft's only language", () => {
  const fi = wording("terms", "fi", "ehdot");
  const en = wording("terms", "en", "terms");
  const sv = wording("terms", "sv", "villkor");
  assert.equal(countedWording([en, fi, sv]), fi);
  assert.equal(countedWording([en]), en);
  assert.equal(countedWording([en, sv]), null);
  assert.equal(countedWording([]), null);
});

test("texts pinned to their versions publish without a problem", () => {
  const wordings = content();
  assert.deepEqual(pinProblems(wordings, pinnedFor(wordings)), []);
});

test("a Finnish text that moved without its version is refused, and the new row is offered", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  const moved = wordings.map((w) => (w.kind === "privacy" ? { ...w, body: `${w.body}!` } : w));
  const [problem, ...rest] = pinProblems(moved, pinned);
  assert.deepEqual(rest, []);
  assert.match(problem ?? "", /^privacy: the fi text of version v1 changed/);
  assert.match(
    problem ?? "",
    new RegExp(fingerprintOf({ title: "privacy", body: "privacy teksti!" })),
  );
});

test("a consent's heading that moved without its version is refused like its body", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  const retitled = wordings.map((w) =>
    w.kind === "research" ? { ...w, title: "Tutkimussuostumus" } : w,
  );
  assert.match(
    pinProblems(retitled, pinned)[0] ?? "",
    /^research: the fi text of version v1 changed/,
  );
});

test("a draft that comes into force, or comes to bind, under its version is refused", () => {
  const draft = { status: "draft", binding: false };
  const wordings = content().map((w) => (w.kind === "terms" ? { ...w, standing: draft } : w));
  const pinned = pinnedFor(wordings);
  assert.deepEqual(pinProblems(wordings, pinned), []);
  for (const standing of [
    { status: "in_force", binding: true },
    { status: "draft", binding: true },
  ]) {
    const flipped = wordings.map((w) => (w.kind === "terms" ? { ...w, standing } : w));
    assert.match(
      pinProblems(flipped, pinned)[0] ?? "",
      /^terms: the fi text of version v1 changed/,
    );
  }
});

test("an English translation's edit moves nothing, a Finnish one does", () => {
  const wordings = [...content(), wording("research", "en", "research text")];
  const pinned = pinnedFor(wordings);
  const english = wordings.map((w) =>
    w.kind === "research" && w.language === "en" ? { ...w, body: "other text" } : w,
  );
  assert.deepEqual(pinProblems(english, pinned), []);
});

test("an English draft without a Finnish text is pinned by its own body", () => {
  const wordings = content().map((w) =>
    w.kind === "terms" ? { ...w, language: "en" as const, body: "DRAFT terms" } : w,
  );
  const pinned = {
    ...pinnedFor(wordings),
    terms: { v1: fingerprintOf({ title: "terms", body: "DRAFT terms" }) },
  };
  assert.deepEqual(pinProblems(wordings, pinned), []);
  const edited = wordings.map((w) => (w.kind === "terms" ? { ...w, body: "DRAFT terms." } : w));
  assert.match(pinProblems(edited, pinned)[0] ?? "", /^terms: the en text of version v1 changed/);
});

test("a new version needs its row at the end, and an old one cannot come back as the newest", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  const bumped = wordings.map((w) =>
    w.kind === "terms" ? { ...w, version: "v2", body: "uudet ehdot" } : w,
  );
  const v2 = fingerprintOf({ title: "terms", body: "uudet ehdot" });
  const [offered] = pinProblems(bumped, pinned);
  assert.match(offered ?? "", new RegExp(`^terms: version v2 has no row; add "v2": "${v2}"`));
  assert.doesNotMatch(offered ?? "", /unchanged/);
  const added = { ...pinned, terms: { ...pinned.terms, v2 } };
  assert.deepEqual(pinProblems(bumped, added), []);
  assert.match(
    pinProblems(wordings, added)[0] ?? "",
    /^terms: version v1 is not the newest row \(v2\)/,
  );
});

test("a new version of an unchanged text says so with the row it offers", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  const bumped = wordings.map((w) => (w.kind === "research" ? { ...w, version: "v2" } : w));
  assert.deepEqual(pinProblems(bumped, pinned), [
    `research: version v2 has no row; add "v2": "${pinned.research.v1}" at the end of research in src/consent-versions.ts. Its text is v1's, unchanged: if the text was to change, change it first`,
  ]);
});

test("every version before a kind's newest keeps its text as its row pins it", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  // Nothing to keep while each kind has one row.
  assert.deepEqual(earlierProblems([], pinned), []);
  const v2 = fingerprintOf({ title: "privacy", body: "uusi teksti" });
  const bumped: Pinned = { ...pinned, privacy: { ...pinned.privacy, v2 } };
  assert.deepEqual(earlierProblems([], bumped), [
    "privacy: version v1 has no kept text; people agreed to it, so its file stays in src/content/earlier/<language>/privacy/v1.md",
  ]);
  const kept = wordings.filter((w) => w.kind === "privacy");
  assert.deepEqual(earlierProblems(kept, bumped), []);
  // An English copy beside the Finnish one changes nothing: the Finnish is counted.
  assert.deepEqual(
    earlierProblems([...kept, wording("privacy", "en", "translated, edited")], bumped),
    [],
  );
});

test("a kept text that was edited, that is the newest, or that has no row is refused", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  const v2 = fingerprintOf({ title: "privacy", body: "uusi teksti" });
  const bumped: Pinned = { ...pinned, privacy: { ...pinned.privacy, v2 } };
  const edited = wording("privacy", "fi", "privacy teksti.");
  assert.deepEqual(earlierProblems([edited], bumped), [
    `privacy: the kept fi text of version v1 is not the one its row pins (${pinned.privacy.v1}, kept ${fingerprintOf(edited)}); it is copied whole and never edited`,
  ]);
  const original = wording("privacy", "fi", "privacy teksti");
  assert.deepEqual(
    earlierProblems([original, wording("privacy", "fi", "uusi teksti", "v2")], bumped),
    ["privacy: v2 is the newest row; its text is the page's own, not a kept one"],
  );
  assert.deepEqual(earlierProblems([original, wording("privacy", "fi", "x", "v0")], bumped), [
    "privacy: the kept text of v0 has no row in src/consent-versions.ts",
  ]);
  // A draft's status is pinned too: a kept draft shown as in force is not the text agreed to.
  const draft = {
    ...wording("terms", "en", "DRAFT"),
    standing: { status: "draft", binding: false },
  };
  const terms: Pinned = {
    ...pinned,
    terms: { v1: fingerprintOf(draft), v2: "0000000000000000" },
  };
  assert.deepEqual(earlierProblems([draft], terms), []);
  assert.match(
    earlierProblems([{ ...draft, standing: { status: "in_force", binding: false } }], terms)[0] ??
      "",
    /^terms: the kept en text of version v1 is not the one its row pins/,
  );
});

test("a row stays as the base has it: never changed, removed or moved, and new ones at the end", () => {
  const base: Pinned = { ...PINNED, research: { a: "1111111111111111", b: "2222222222222222" } };
  assert.deepEqual(historyProblems(base, base), []);
  assert.deepEqual(historyProblems({}, PINNED), [], "before the pin began");
  assert.deepEqual(
    historyProblems(base, { ...base, research: { ...base.research, c: "3333333333333333" } }),
    [],
  );
  assert.deepEqual(
    historyProblems(base, { ...base, research: { a: "1111111111111111", b: "9999999999999999" } }),
    [
      "research: the row of b changed (2222222222222222, now 9999999999999999); a row is never changed: people agreed to the text it pins. A changed text is a new version, with a row of its own at the end",
    ],
  );
  assert.deepEqual(historyProblems(base, { ...base, research: { b: "2222222222222222" } }), [
    "research: the row of a is gone; a row is never removed",
    "research: the row of b moved; a new row is added at the end",
  ]);
  assert.deepEqual(
    historyProblems(base, {
      ...base,
      research: { c: "3333333333333333", a: "1111111111111111", b: "2222222222222222" },
    }),
    [
      "research: the row of a moved; a new row is added at the end",
      "research: the row of b moved; a new row is added at the end",
    ],
  );
});

test("a kind without a text, without a version, or with two versions is refused", () => {
  const wordings = content();
  const pinned = pinnedFor(wordings);
  assert.deepEqual(
    pinProblems(
      wordings.filter((w) => w.kind !== "research"),
      pinned,
    ),
    ["research: no text on the site"],
  );
  const unversioned = wordings.map((w) => (w.kind === "terms" ? { ...w, version: undefined } : w));
  assert.deepEqual(pinProblems(unversioned, pinned), ["terms: no consent_version"]);
  const two = [...wordings, wording("privacy", "en", "privacy", "v2")];
  assert.deepEqual(pinProblems(two, pinned), [
    "privacy: one consent_version in one language and another in another",
  ]);
  const unbound = [
    ...wordings.filter((w) => w.kind !== "terms"),
    wording("terms", "en", "terms"),
    wording("terms", "sv", "villkor"),
  ];
  assert.match(pinProblems(unbound, pinned)[0] ?? "", /^terms: no Finnish text, and more than one/);
});

test("versions.json names each kind's version, fingerprint, language, address and day", () => {
  const wordings = content();
  const document = versionsDocument(wordings, pinnedFor(wordings), ORIGIN);
  assert.deepEqual(Object.keys(document), [...CONSENT_KINDS]);
  assert.deepEqual(document.research, {
    version: "v1",
    hash: fingerprintOf({ title: "research", body: "research teksti" }),
    language: "fi",
    url: "https://kuutti.app/legal/privacy/#research-v1",
    dated: "2026-10-06",
  });
  assert.equal(document.terms.url, "https://kuutti.app/legal/terms/#terms-v1");
  assert.equal(
    document.special_category.url,
    "https://kuutti.app/legal/privacy/#special_category-v1",
  );
});

